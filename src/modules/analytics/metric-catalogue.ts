/** Validated at module load: an invalid definition fails fast in every environment and test. */
export const METRIC_CATALOGUE: readonly MetricDefinition[] = Object.freeze(
  definitions.map((definition) => metricDefinitionSchema.parse(definition)),
);

const BY_KEY = new Map(METRIC_CATALOGUE.map((metric) => [metric.key, metric]));
if (BY_KEY.size !== METRIC_CATALOGUE.length) throw new Error("Duplicate metric keys in catalogue");

export type MetricKey = (typeof definitions)[number]["key"];

export function getMetric(key: string): MetricDefinition {
  const metric = BY_KEY.get(key);
  if (!metric) throw new Error(`Unknown metric: ${key}`);
  return metric;
}

export function availableMetrics(): MetricDefinition[] {
  return METRIC_CATALOGUE.filter((m) => m.availability.status === "available");
}
