import { z } from "zod";

/**
 * PEOS metric catalogue (05_ANALYTICS_METRICS.md "Metric Governance", ADR 0019).
 *
 * Every metric declares name, definition, formula, source, frequency, owner and caveats. Only
 * metrics that can be computed truthfully from persisted data are `available`; the remaining
 * specification KPIs are listed as `unavailable` with the reason and the phase that unlocks them,
 * so the catalogue is honest about what PEOS can and cannot measure yet.
 *
 * The catalogue lives in code, next to the calculators that implement it, so a stated formula
 * cannot drift from the computed one. Changes are versioned (`version`, `revised`) and reviewed
 * through git; the API serves it read-only.
 */
export const METRIC_CATEGORIES = [
  "projects",
  "evidence",
  "skills",
  "certifications",
  "goals",
  "ai",
  "architecture",
  "engineering",
] as const;

const nonBlank = z.string().trim().min(1);

export const metricDefinitionSchema = z
  .object({
    key: z.string().regex(/^[a-z]+(\.[a-z_]+)+$/, "dotted lower-case key"),
    name: nonBlank,
    category: z.enum(METRIC_CATEGORIES),
    definition: nonBlank,
    formula: nonBlank,
    source: z.array(nonBlank).min(1),
    frequency: nonBlank,
    owner: nonBlank,
    caveats: z.array(nonBlank).min(1),
    /**
     * count = single number; distribution = counts per bucket; ratio = 0–1 share with numerator and
     * denominator in the breakdown; score = 0–100 explained by components; matrix = counts per
     * pair of categories.
     */
    valueType: z.enum(["count", "distribution", "ratio", "score", "matrix"]),
    /** point_in_time = current state; period = depends on the dashboard date range. */
    temporal: z.enum(["point_in_time", "period"]),
    /** Where the spec names this metric. */
    specRef: nonBlank,
    /** Human-readable drill-down target (the UI maps the key to a filtered list). */
    drillDown: z.string().nullable(),
    availability: z.discriminatedUnion("status", [
      z.object({ status: z.literal("available") }),
      z.object({ status: z.literal("unavailable"), reason: nonBlank, plannedPhase: nonBlank }),
    ]),
    version: z.number().int().positive(),
    introduced: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
    revised: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
  })
  .strict();

export type MetricDefinition = z.infer<typeof metricDefinitionSchema>;

